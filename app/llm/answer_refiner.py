# app/llm/answer_refiner.py

import os

from dotenv import load_dotenv
from openai import OpenAI

load_dotenv()

API_KEY = os.getenv("FINAL_ANSWER_API_KEY")

if not API_KEY:
    raise RuntimeError("FINAL_ANSWER_API_KEY is not set.")

MODEL_NAME = os.getenv("FINAL_ANSWER_MODEL")

if not MODEL_NAME:
    raise RuntimeError("FINAL_ANSWER_MODEL is not set.")

client = OpenAI(api_key=API_KEY)


def refine_answer(question, draft_answer):
    """
    Refine a draft answer generated by Gemini or Hugging Face.

    This function makes exactly ONE OpenAI API call.

    It does not:
    - perform repository retrieval
    - access ChromaDB
    - generate embeddings
    - analyze repository files
    - call Gemini
    - call Hugging Face

    If refinement fails, the original draft answer is returned.
    """

    if not question or not question.strip():
        return draft_answer

    if not draft_answer or not draft_answer.strip():
        return draft_answer

    prompt = f"""
You are the final answer editor for an AI software engineering assistant.

Your job is to improve the draft answer written for a software developer.

User Question:
------------------
{question}
------------------

Draft Answer:
------------------
{draft_answer}
------------------

Improve the draft answer according to these rules:

1. Preserve all technical facts from the draft answer.

2. Do not invent files, folders, classes, functions, methods,
   variables, dependencies, APIs, configurations, or implementation
   details.

3. Do not add information that is not supported by the draft answer.

4. Make the answer clear, accurate, concise, and useful to a
   software developer.

5. Fix grammar, wording, repetition, and awkward phrasing.

6. Preserve important technical details.

7. Use clean Markdown formatting.

8. Use **bold** for important concepts when useful.

9. Use `backticks` for files, functions, classes, variables,
   commands, API endpoints, and other code identifiers.

10. Use bullet points when presenting multiple items.

11. Use numbered lists when explaining steps or workflows.

12. Do not unnecessarily add headings to short answers.

13. Do not mention:
    - Gemini
    - Hugging Face
    - OpenAI
    - AI models
    - APIs used to generate the answer
    - RAG
    - embeddings
    - vector databases
    - retrieval
    - prompts
    - internal processing

14. Do not use phrases such as:
    "Based on the draft"
    "According to the generated answer"
    "The model determined"
    "The retrieved context shows"

15. Do not change the meaning of the answer.

16. If the draft answer says that the available information is
    insufficient, preserve that conclusion.

17. Return ONLY the improved final answer in clean Markdown.
"""

    try:
        print()
        print("=" * 60)
        print("FINAL ANSWER REFINEMENT")
        print("=" * 60)
        print("Provider: OpenAI")
        print(f"Model: {MODEL_NAME}")
        print("API calls for refinement: 1")

        response = client.responses.create(
            model=MODEL_NAME,
            input=prompt
        )

        if response is None:
            raise RuntimeError("OpenAI returned no response.")

        refined_answer = response.output_text

        if not refined_answer or not refined_answer.strip():
            raise RuntimeError("OpenAI returned an empty answer.")

        print()
        print("=" * 60)
        print("FINAL ANSWER REFINEMENT SUCCESSFUL")
        print("=" * 60)
        print(f"Final answer length: {len(refined_answer.strip())} characters")

        return refined_answer.strip()

    except Exception as error:
        print()
        print("=" * 60)
        print("FINAL ANSWER REFINEMENT FAILED")
        print("=" * 60)
        print(f"Error type: {type(error).__name__}")
        print(f"Error: {error}")
        print("Returning the original draft answer.")

        return draft_answer.strip()


if __name__ == "__main__":
    test_question = "Where is the OpenAI client configured?"

    test_draft = """
The OpenAI client is configured in `client.py`.

The file imports `OpenAI` and creates an OpenAI client instance.
The client is then used to send completion requests.
"""

    print()
    print("=" * 60)
    print("OPENAI ANSWER REFINER TEST")
    print("=" * 60)

    final_answer = refine_answer(
        test_question,
        test_draft
    )

    print()
    print("=" * 60)
    print("REFINED ANSWER")
    print("=" * 60)
    print()
    print(final_answer)